"""
AkerGate - Automated Serverless Telegram Deployment Engine
Automates deployment and configuration for:
1. Official Telegram Serverless (tgcloud.ai)
2. Cloudflare Workers (Wrangler & Pre-bundled Standalone)
Zero external heavy dependencies. Zero emojis.
"""

import os
import sys
import subprocess
from pathlib import Path
from typing import Tuple, Optional
from akergate.config import load_config, save_config
from akergate.core.storage import get_telegram_secret
from akergate.sentry.notifier import set_telegram_webhook

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
TGCLOUD_DIR = PROJECT_ROOT / "telegram_backends" / "telegram_serverless"
CLOUDFLARE_DIR = PROJECT_ROOT / "telegram_backends" / "cloudflare_worker"

def sync_telegram_serverless_config() -> Tuple[bool, str]:
    """
    Automatically injects the host credentials into tgcloud/config.js.
    Eliminates manual editing of JavaScript configuration files.
    """
    config = load_config()
    tg_cfg = config.get("telegram", {})
    chat_id = tg_cfg.get("allowed_chat_id", 0)
    secret = get_telegram_secret()
    interval = tg_cfg.get("interval_seconds", 300)

    if not secret:
        return False, "No Telegram shared secret configured on this host."
    if not chat_id:
        return False, "No Telegram Allowed Chat ID configured."

    target_file = TGCLOUD_DIR / "tgcloud" / "lib" / "config.js"
    target_file.parent.mkdir(parents=True, exist_ok=True)

    # Clean up legacy root config.js if it exists to prevent stray file warning from @tgcloud/cli
    legacy_file = TGCLOUD_DIR / "tgcloud" / "config.js"
    if legacy_file.exists():
        try:
            legacy_file.unlink()
        except OSError:
            pass

    content = f"""/**
 * AkerGate Telegram Serverless Configuration
 * Auto-generated by AkerGate Deployment Engine.
 * Zero emojis, clean symbols only.
 */

export const CONFIG = {{
  ALLOWED_CHAT_ID: {chat_id},
  SHARED_SECRET: "{secret}",
  INTERVAL_SECONDS: {interval}
}};
"""
    try:
        target_file.write_text(content, encoding="utf-8")
        return True, f"Successfully auto-configured {target_file.relative_to(PROJECT_ROOT)}"
    except Exception as e:
        return False, f"Failed to write config.js: {e}"

def sync_cloudflare_worker_bundle() -> Tuple[bool, str]:
    """
    Creates a pre-configured, self-contained worker.bundle.js for Cloudflare.
    Can be pasted directly into Cloudflare Web Dashboard without setting secrets manually.
    """
    config = load_config()
    tg_cfg = config.get("telegram", {})
    chat_id = tg_cfg.get("allowed_chat_id", 0)
    bot_token = tg_cfg.get("bot_token", "")
    secret = get_telegram_secret()
    interval = tg_cfg.get("interval_seconds", 300)

    source_file = CLOUDFLARE_DIR / "worker.js"
    target_file = CLOUDFLARE_DIR / "worker.bundle.js"

    if not source_file.exists():
        return False, "Source worker.js not found."

    code = source_file.read_text(encoding="utf-8")

    # Prepend embedded credentials header
    header = f"""/**
 * AkerGate - Pre-bundled Standalone Cloudflare Worker
 * Auto-generated by AkerGate Deployment Engine.
 * Ready for 1-click paste into Cloudflare Web Dashboard.
 * Zero emojis, clean symbols only.
 */

const EMBEDDED_BOT_TOKEN = "{bot_token}";
const EMBEDDED_ALLOWED_CHAT_ID = "{chat_id}";
const EMBEDDED_SHARED_SECRET = "{secret}";
const EMBEDDED_INTERVAL_SECONDS = "{interval}";

"""
    # Replace env references to fallback to embedded constants if env vars are unset
    patched_code = code.replace(
        'const senderId = String(message.from.id);',
        'const senderId = String(message.from ? message.from.id : message.chat.id);'
    ).replace(
        'const allowedId = String(env.ALLOWED_CHAT_ID);',
        'const allowedId = String(env.ALLOWED_CHAT_ID || EMBEDDED_ALLOWED_CHAT_ID);'
    ).replace(
        'const botToken = env.BOT_TOKEN;',
        'const botToken = env.BOT_TOKEN || EMBEDDED_BOT_TOKEN;'
    ).replace(
        'const secret = env.SHARED_SECRET;',
        'const secret = env.SHARED_SECRET || EMBEDDED_SHARED_SECRET;'
    ).replace(
        'const interval = parseInt(env.INTERVAL_SECONDS || "300", 10);',
        'const interval = parseInt(env.INTERVAL_SECONDS || EMBEDDED_INTERVAL_SECONDS || "300", 10);'
    )

    try:
        target_file.write_text(header + patched_code, encoding="utf-8")
        return True, f"Successfully created ready-to-paste bundle: {target_file.relative_to(PROJECT_ROOT)}"
    except Exception as e:
        return False, f"Failed to generate worker.bundle.js: {e}"

def run_tgcloud_push(cli_token: Optional[str] = None) -> Tuple[bool, str]:
    """
    Executes 'npx @tgcloud/cli push' in the telegram_serverless directory.
    Uses TGCLOUD_TOKEN if supplied or saved in config for automated non-interactive deployment.
    Returns (success, stdout/stderr output).
    """
    sync_ok, sync_msg = sync_telegram_serverless_config()
    if not sync_ok:
        return False, sync_msg

    env = os.environ.copy()
    if cli_token:
        env["TGCLOUD_TOKEN"] = cli_token.strip()
    else:
        cfg = load_config()
        stored_token = cfg.get("telegram", {}).get("tgcloud_token")
        if stored_token:
            env["TGCLOUD_TOKEN"] = stored_token.strip()

    try:
        proc = subprocess.run(
            ["npx", "--yes", "@tgcloud/cli", "push"],
            cwd=str(TGCLOUD_DIR),
            capture_output=True,
            text=True,
            env=env,
            timeout=60
        )
        output = (proc.stdout + "\n" + proc.stderr).strip()
        if proc.returncode == 0:
            return True, output if output else "Deployment to Telegram Serverless succeeded."
        return False, output if output else f"tgcloud push failed with exit code {proc.returncode}"
    except subprocess.TimeoutExpired:
        return False, "Deployment timed out after 60 seconds."
    except Exception as e:
        return False, str(e)

def run_wrangler_deploy() -> Tuple[bool, str, Optional[str]]:
    """
    Executes 'npx wrangler deploy' in the cloudflare_worker directory.
    Attempts to extract the deployed worker URL from output.
    Returns (success, output, worker_url).
    """
    sync_ok, sync_msg = sync_cloudflare_worker_bundle()
    if not sync_ok:
        return False, sync_msg, None

    try:
        proc = subprocess.run(
            ["npx", "--yes", "wrangler", "deploy", "worker.bundle.js"],
            cwd=str(CLOUDFLARE_DIR),
            capture_output=True,
            text=True,
            timeout=90
        )
        output = (proc.stdout + "\n" + proc.stderr).strip()
        worker_url = None

        # Attempt to parse deployed URL (e.g., https://akergate-telegram-bot.yourname.workers.dev)
        for line in output.splitlines():
            if "workers.dev" in line:
                for word in line.split():
                    if word.startswith("http://") or word.startswith("https://"):
                        worker_url = word.strip()
                        break

        if proc.returncode == 0:
            return True, output, worker_url
        return False, output, None
    except subprocess.TimeoutExpired:
        return False, "Wrangler deploy timed out after 90 seconds.", None
    except Exception as e:
        return False, str(e), None
